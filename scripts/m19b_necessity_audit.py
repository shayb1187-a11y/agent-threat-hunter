def dedale_labels(external: Path) -> dict[str, Any]:
    path = external / "dedale" / "labels" / "dedale_class1_labels.json"
    if not path.is_file():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def dedale_ground_truth(external: Path, day_date: str) -> dict[str, Any]:
    """The labelled stage for one DEDALE day, and which domain its evidence lives in.

    DEDALE's labels name ``host;channel;record_id``. Sysmon 1 and the PowerShell
    channels are process evidence; the label file states outright that no Security
    channel event is labelled, so the *identity* half of any DEDALE chain is unlabelled
    by construction -- a fact this audit must report rather than work around, because a
    cross-domain benchmark built on it could never score the identity side.
    """
    labels = dedale_labels(external)
    scenario = (labels.get("scenarios") or {}).get("apt") or {}
    stage = (scenario.get("stages") or {}).get(day_date)
    if stage is None:
        return {"labelled": False, "note": f"no labelled events on {day_date}"}
    refs = stage.get("refs", [])
    channels = Counter()
    hosts = Counter()
    for ref in refs:
        parts = dict(p.split("=", 1) for p in ref.split(";") if "=" in p)
        channels[parts.get("channel", "")] += 1
        hosts[parts.get("host", "")] += 1
    return {
        "labelled": True,
        "date": day_date,
        "labelled_events": len(refs),
        "hosts": dict(hosts),
        "channels": dict(channels),
        "domains_of_labelled_evidence": ["endpoint"],
        "note": (
            "Every labelled channel is Sysmon or PowerShell, i.e. endpoint evidence. "
            "The label file states that no Security-channel event is labelled, so the "
            "identity stage of this chain has no ground truth."
        ),
        "scenario_note": scenario.get("note", ""),
    }


def synthetic_ground_truth(data_dir: Path) -> dict[str, Any]:
    path = data_dir / "ground_truth.json"
    if not path.is_file():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def git_commits_for(pattern: str, kind: str) -> int:
    """How many commits added or removed a literal (``-S``), or touched a path.

    Used for the held-out question, and it is the only honest answer available: a case
    whose ids and fixtures have been edited across many commits has been iterated
    against in this repository, whatever anybody intended, and cannot be presented as
    held-out evidence in a benchmark.
    """
    args = ["git", "log", "--oneline"]
    args += ["-S", pattern] if kind == "content" else ["--", pattern]
    try:
        out = subprocess.run(
            args, cwd=ROOT, capture_output=True, text=True, check=False, timeout=180,
        )
    except Exception:  # noqa: BLE001
        return -1
    if out.returncode != 0:
        return -1
    return len([line for line in out.stdout.splitlines() if line.strip()])


def tuning_history(spec: dict[str, Any], rule_ids: Iterable[str]) -> dict[str, Any]:
    """Commits that touched a case's inputs: its corpus path and its rules' ids."""
    rules = sorted(set(rule_ids))
    return {
        "commits_touching_source_path": git_commits_for(
            _repo_relative(spec["path"]), "path",
        ),
        "commits_mentioning_rule": {r: git_commits_for(r, "content") for r in rules},
    }


def _repo_relative(path: Path) -> str:
    try:
        return str(Path(path).resolve().relative_to(ROOT)).replace("\\", "/")
    except ValueError:
        return str(path)


