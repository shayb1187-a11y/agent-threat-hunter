def pipeline(telemetry: Telemetry) -> tuple[list[Any], list[Any], Any]:
    hunt = run_hunt(telemetry, config=HuntConfig())
    environment = build_environment_model(telemetry)
    assessments = assess_findings(hunt.findings, environment)
    cases = correlate(hunt.findings, telemetry, set_aside=set_aside_ids(assessments))
    return list(hunt.findings), list(cases), environment


def row_counts(telemetry: Telemetry) -> dict[str, int]:
    return {
        "process": int(len(telemetry.table(EVENT_PROCESS))),
        "network": int(len(telemetry.table(EVENT_NETWORK))),
        "logon": int(len(telemetry.table(EVENT_LOGON))),
        "control": int(len(telemetry.table(EVENT_CONTROL))),
    }


