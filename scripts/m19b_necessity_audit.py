def _limitations_section(payload: dict[str, Any]) -> str:
    out = ["## Limitations of this audit\n"]
    out.append(
        "* **Condition 3 is a rule, not a judgement.** `_synthesis_statement` derives "
        "its answer from conditions 1 and 2 rather than reasoning about each case, so "
        "it can neither rescue a case the first two conditions reject nor reject one "
        "they accept. On this corpus the question never arises -- one case passes the "
        "first two conditions -- but on a richer corpus condition 3 would need a human "
        "reading rather than this function.\n"
        "* **Condition 2 is strict about a finding that spans two domains.** A single "
        "finding relevant to two specialists counts as one stage. `ATH-003` is the "
        "only rule this affects, and the choice is stated rather than hidden: a "
        "looser reading would qualify any case containing `ATH-003`, and the planner "
        "would still be choosing between two specialists reading the same rows.\n"
        "* **Domain membership is computed from `fields_used`, so it can over-count.** "
        "`ATH-003` reads only the network table yet declares `process_name` and "
        "`process_id`, which map to the process-execution channel -- so the endpoint "
        "specialist is eligible on a case built from network rows alone. That is the "
        "pipeline's own behaviour, reported as measured, not an artefact of this "
        "script.\n"
        "* **'Held out' is answered by `git log`, which is a lower bound.** A rule "
        "tuned by editing a threshold in a file the rule id does not appear in is not "
        "counted.\n"
        "* **Unlabelled corpora cannot be scored on condition 1's 'belongs to the "
        "labelled attack chain' clause.** For `flaws_cloud` and `comiset` the audit "
        "falls back to the plan's second clause -- the same actor/host/time story the "
        "case's findings tell -- which the correlator has already enforced by "
        "construction.\n"
        "* **No model was called and no rule was changed**, so nothing here is a "
        "statement about detection quality.\n"
    )
    return "\n".join(out)


def _corpus_distribution(detail: list[dict[str, Any]]) -> str:
    by_domains = Counter(tuple(c["domains"]) for c in detail)
    by_first = Counter(c["first_step_domain_specialists"] for c in detail)
    by_eligible = Counter(c["whole_run_specialists_eligible"] for c in detail)
    lines = ["", "```"]
    lines.append("domains with material evidence:")
    for domains, n in by_domains.most_common():
        lines.append(f"  {', '.join(domains) or 'none':40s} {n:5d} cases")
    lines.append("domain specialists eligible at step 0:")
    for k, n in sorted(by_first.items()):
        lines.append(f"  {k:40d} {n:5d} cases")
    lines.append("specialists_eligible over the whole run (arm A's number):")
    for k, n in sorted(by_eligible.items()):
        lines.append(f"  {k:40d} {n:5d} cases")
    lines.append("```")
    return "\n".join(lines)


def head() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--external", type=Path, default=DEFAULT_EXTERNAL)
    parser.add_argument(
        "--corpora", choices=("all", "fast", "dedale"), default="all",
        help="'fast' skips the multi-hundred-megabyte DEDALE slices.",
    )
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument(
        "--limit-cases", type=int, default=None,
        help="Audit at most N cases per corpus. Development only; the committed run "
             "uses every case.",
    )
    parser.add_argument(
        "--render-only", action="store_true",
        help="Re-render AUDIT.md from an existing AUDIT.json without re-auditing. The "
             "measurements are in the JSON; this exists so the prose can be corrected "
             "without a twenty-minute re-run silently changing a number beside it.",
    )
    args = parser.parse_args()

    if args.render_only:
        payload = json.loads((args.out / "AUDIT.json").read_text(encoding="utf-8"))
        (args.out / "AUDIT.md").write_text(render_markdown(payload), encoding="utf-8")
        print(f"re-rendered {args.out / 'AUDIT.md'} from AUDIT.json (no corpus loaded).")
        return 0

    specs = corpus_specs(args.external.resolve())
    if args.corpora != "all":
        specs = [s for s in specs if s["group"] == args.corpora]

    corpora: list[CorpusAudit] = []
    for spec in specs:
        started = time.perf_counter()
        print(f"auditing {spec['name']} ...", flush=True)
        corpus = audit_corpus(spec, args.external.resolve(), args.limit_cases)
        corpora.append(corpus)
        print(
            f"  {corpus.cases} cases, {len(corpus.qualifying)} qualifying, "
            f"{time.perf_counter() - started:.1f}s"
            + (f" [{corpus.error}]" if corpus.error else ""),
            flush=True,
        )

    if args.corpora in ("all", "fast"):
        for corpus in audit_synthetic():
            corpora.append(corpus)
            print(
                f"auditing {corpus.name} ... {corpus.cases} cases, "
                f"{len(corpus.qualifying)} qualifying", flush=True,
            )

    body = [c.to_dict() for c in corpora]
    payload: dict[str, Any] = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "head": head(),
        "task": "M19b T4 cross-specialist necessity audit",
        "necessity_test": {
            "1": "two or more domain specialists have materially relevant evidence",
            "2": "removing a domain removes a stage, not a duplicate",
            "3": "cross-domain synthesis could change verdict, priority or next action",
            "note": "the ATT&CK mapper is not a domain specialist",
        },
        "corpora": body,
    }
    payload["totals"] = {
        "corpora_audited": len([c for c in corpora if not c.error]),
        "corpora_unavailable": [c.name for c in corpora if c.error],
        "cases_audited": sum(len(c.case_audits) for c in corpora),
        "qualifying_cases": sum(len(c.qualifying) for c in corpora),
        "qualifying": [
            {"corpus": c.name, "case_id": a.case_id, "provenance": c.provenance}
            for c in corpora for a in c.qualifying
        ],
    }
    payload["audit_digest"] = audit_digest(body)

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "AUDIT.json").write_text(
        json.dumps(payload, indent=2, default=str), encoding="utf-8",
    )
    (args.out / "AUDIT.md").write_text(render_markdown(payload), encoding="utf-8")
    print(
        f"\n{payload['totals']['cases_audited']} cases audited, "
        f"{payload['totals']['qualifying_cases']} qualifying. "
        f"Wrote {args.out / 'AUDIT.json'} and {args.out / 'AUDIT.md'}."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
