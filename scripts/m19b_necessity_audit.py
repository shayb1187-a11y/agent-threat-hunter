def audit_corpus(
    spec: dict[str, Any], external: Path, limit: int | None = None,
) -> CorpusAudit:
    name = spec["name"]
    path = Path(spec["path"])
    if not path.exists():
        return CorpusAudit(
            name=name, provenance=spec["provenance"], source=spec["source"],
            rows={}, corpus_channels=(), findings=0, cases=0,
            notes=spec["notes"],
            error=f"UNAVAILABLE: {path} does not exist in this checkout",
        )

    started = time.perf_counter()
    try:
        telemetry = spec["load"]()
    except Exception as exc:  # noqa: BLE001 -- a failed load is a reported result
        return CorpusAudit(
            name=name, provenance=spec["provenance"], source=spec["source"],
            rows={}, corpus_channels=(), findings=0, cases=0,
            notes=spec["notes"], error=f"LOAD FAILED: {type(exc).__name__}: {exc}",
        )
    load_seconds = time.perf_counter() - started

    findings, cases, environment = pipeline(telemetry)
    observable = environment.observable_channels
    ground_truth = _corpus_ground_truth(name, external)
    tuning = tuning_history(spec, {f.rule_id for f in findings})

    # attack_data_aws is the one external corpus with a per-case label: the capture
    # file name carries the ATT&CK technique. It is read here rather than left to the
    # corpus-level note, because "which domain does each stage's evidence live in" is a
    # per-case question and answering it corpus-wide would be answering a different one.
    per_case = _capture_labels(telemetry, cases) if name == "attack_data_aws" else {}
    # One pass over the corpus's event ids for all its cases; see event_id_index.
    index = event_id_index(telemetry)

    audits: list[CaseAudit] = []
    for case in cases[: limit or len(cases)]:
        audits.append(audit_case(
            case,
            corpus=name, provenance=spec["provenance"],
            telemetry=telemetry, findings=findings, cases=cases,
            environment=environment, corpus_channels=observable,
            ground_truth={**ground_truth, **per_case.get(case.case_id, {})},
            tuned_against=tuning,
            held_out=False,
            evidence_index=index,
        ))

    notes = spec["notes"] + f" Loaded in {load_seconds:.1f}s."
    return CorpusAudit(
        name=name, provenance=spec["provenance"], source=spec["source"],
        rows=row_counts(telemetry),
        corpus_channels=tuple(sorted(c.value for c in observable)),
        findings=len(findings), cases=len(cases), case_audits=audits, notes=notes,
    )


def _capture_labels(
    telemetry: Telemetry, cases: Sequence[Any],
) -> dict[str, dict[str, Any]]:
    """The attack_data capture label per case, as ``scripts/m19_ablation.py`` derives it.

    The technique is the first ``__``-separated component of the capture file name, and
    the capture is the ``File=`` half of a row's ``source_ref``. A case drawing evidence
    from more than one capture gets no technique rather than an arbitrary one.
    """
    capture_of: dict[str, str] = {}
    for event_type in (EVENT_PROCESS, EVENT_NETWORK, EVENT_LOGON, EVENT_CONTROL):
        frame = telemetry.table(event_type)
        if frame.empty:
            continue
        refs = frame["source_ref"].astype("string").fillna("")
        for event_id, ref in zip(frame["event_id"], refs):
            for part in str(ref).split(";"):
                if part.startswith("File="):
                    capture_of[str(event_id)] = part[len("File="):]

    labels: dict[str, dict[str, Any]] = {}
    for case in cases:
        captures = sorted({capture_of.get(e, "") for e in case.event_ids} - {""})
        labels[case.case_id] = {
            "captures": captures,
            "labelled_technique": (
                captures[0].split("__", 1)[0] if len(captures) == 1 else ""
            ),
            "stage_domains": {"the whole capture": "control_plane"},
        }
    return labels


def _corpus_ground_truth(name: str, external: Path) -> dict[str, Any]:
    if name.startswith("dedale:"):
        day = {
            "dedale:D02": "2024-12-24", "dedale:D03": "2024-12-25",
            "dedale:D07": "2024-12-29", "dedale:D15": "2025-01-06",
            "dedale:D18": "2025-01-09",
        }[name]
        return dedale_ground_truth(external, day)
    if name == "attack_data_aws":
        return {
            "labelled": True,
            "kind": "capture file name carries the ATT&CK technique",
            "domains_of_labelled_evidence": ["control_plane"],
            "note": (
                "Each capture is one technique. Every row the adapter keeps is a "
                "CloudTrail management or authentication event, so the whole labelled "
                "chain lives in one or two channels of one table."
            ),
        }
    if name in {"comiset", "comiset_m17_freeze"}:
        return {
            "labelled": False,
            "note": (
                "COMISET ships no attack labels usable here; M17 recorded it as an "
                "unlabelled real corpus. Any 'chain' is the correlator's, not ground "
                "truth's."
            ),
        }
    if name == "flaws_cloud":
        return {
            "labelled": False,
            "note": (
                "No labels. The published narrative describes levels of a CTF, not "
                "event ids, so no stage of any case can be confirmed."
            ),
        }
    return {"labelled": False, "note": "no attack ground truth for this corpus"}


