def _candidates_section(payload: dict[str, Any]) -> str:
    """Qualifying cases, ranked by provenance: real labelled first, synthetic last."""
    candidates = []
    for corpus in payload["corpora"]:
        for case in corpus["cases_detail"]:
            if case["qualifies"]:
                candidates.append((corpus, case))
    candidates.sort(key=lambda pair: (
        _PROVENANCE_RANK.get(pair[0]["provenance"], 9),
        -pair[1]["independent_evidence_sources"],
        -len(pair[1]["domains"]),
        pair[1]["case_id"],
    ))

    out = ["## Qualifying candidates, ranked by provenance\n"]
    if not candidates:
        out.append(
            "**None.** No case in any corpus this repository can load today passes all "
            "three conditions. MEASURED.\n"
        )
        return "\n".join(out)
    rows = []
    for rank, (corpus, case) in enumerate(candidates, start=1):
        rules = ", ".join(case["rule_ids"])
        tuned = case["tuned_against"].get("commits_mentioning_rule", {})
        rows.append([
            str(rank),
            f"`{corpus['corpus']}` / `{case['case_id']}`",
            corpus["provenance"],
            ", ".join(case["domains"]),
            str(case["independent_evidence_sources"]),
            rules,
            "no -- " + ", ".join(f"{r}: {n} commits" for r, n in sorted(tuned.items())),
        ])
    out.append(_table(rows, [
        "#", "case", "provenance", "domains", "independent sources", "rules",
        "held out?",
    ]))
    out.append("")
    out.append(
        "*Held out* is answered by `git log`: a rule id edited across many commits, or "
        "a fixture rewritten repeatedly, has been iterated against in this repository "
        "whatever anyone intended. On this evidence no existing case can be presented "
        "as held-out data. MEASURED.\n"
    )
    return "\n".join(out)


def _near_miss_section(payload: dict[str, Any]) -> str:
    """Cases that carry two domains and still fail, and precisely where.

    Worth its own section because these are the cases a reader would otherwise assume
    the audit had overlooked, and because each one names a different gap: a rule that
    spans two domains inside one finding, a corpus that has both domains but never in
    one case, a corpus that has the rows and raises no case at all.
    """
    rows = []
    for corpus in payload["corpora"]:
        for case in corpus["cases_detail"]:
            if case["qualifies"] or len(case["domains"]) < 2:
                continue
            rows.append([
                f"`{corpus['corpus']}` / `{case['case_id']}`",
                ", ".join(case["domains"]),
                ", ".join(case["rule_ids"]),
                str(case["first_step_domain_specialists"]),
                case["failure_reason"],
            ])

    out = ["## Near misses: two domains present, still not qualifying\n"]
    if not rows:
        out.append(
            "None. Every non-qualifying case in every corpus carries evidence for at "
            "most one domain -- the failure is never subtle. MEASURED.\n"
        )
    else:
        out.append(_table(rows, [
            "case", "domains", "rules", "domain specialists at step 0", "why it fails",
        ]))
        out.append("")

    # Corpora that carry two domains' worth of telemetry and never put them in one case.
    split = []
    for corpus in payload["corpora"]:
        seen = {tuple(c["domains"]) for c in corpus["cases_detail"]}
        singles = {d[0] for d in seen if len(d) == 1}
        if len(singles) >= 2:
            split.append((corpus, sorted(singles)))
    if split:
        out.append(
            "### Corpora whose cases split cleanly along the domain boundary\n"
        )
        out.append(
            "These corpora carry two domains' worth of telemetry and raise cases in "
            "both -- never in the same case. This is the shape that matters most for "
            "T5, because it is the shape a correlator change (not a data change) "
            "would address:\n"
        )
        out.append(_table([
            [f"`{corpus['corpus']}`", ", ".join(domains),
             str(corpus["cases_audited"]),
             " / ".join(
                 f"{d}: {sum(1 for c in corpus['cases_detail'] if tuple(c['domains']) == (d,))}"
                 for d in domains
             )]
            for corpus, domains in split
        ], ["corpus", "domains raised", "cases", "split"]))
        out.append("")
    return "\n".join(out)


def _structural_section(payload: dict[str, Any]) -> str:
    """Why the corpora look the way they do -- read out of the code, not the data.

    The counts here are the audit's, but the *reason* is structural and checkable in
    two files, which matters: a shortage that follows from the rule catalogue and the
    correlator's link predicates cannot be fixed by fetching more data.
    """
    # Quoted, not imported. These two constants were the correlator's cross-domain
    # allowlist at 41c0d97, the commit this audit measured; the M19b link task deleted
    # them and replaced them with a channel-family predicate. The audit is a statement
    # about the code as it stood, so the values it prints are frozen here rather than
    # read from a module that no longer defines them -- which also keeps
    # `--render-only` able to reproduce `AUDIT.md` byte for byte.
    _AUTH_RULES = frozenset({"ATH-005", "ATH-006"})
    _REMOTE_EXEC_RULES = frozenset({"ATH-007"})
    import ath.hunting.rules  # noqa: F401 -- registers the catalogue
    from ath.environment.coverage import channels_for_fields
    from ath.evaluation.necessity import channel_domains
    from ath.hunting import all_detectors

    by_domains: Counter[tuple[str, ...]] = Counter()
    for detector in all_detectors():
        channels = (
            set(detector.channels) if detector.channels
            else channels_for_fields(detector.fields_used)
        )
        by_domains[tuple(sorted(channel_domains(channels)))] += 1

    rows = [
        [", ".join(domains) or "none", str(count),
         ", ".join(sorted(
             d.rule_id for d in all_detectors()
             if tuple(sorted(channel_domains(
                 set(d.channels) if d.channels else channels_for_fields(d.fields_used)
             ))) == domains
         ))]
        for domains, count in sorted(by_domains.items(), key=lambda kv: -kv[1])
    ]

    out = ["## Why the corpora look like this (VERIFIED FROM CODE)\n"]
    out.append(
        "A case is multi-domain only if its member findings are, and the rule "
        "catalogue decides that before any corpus is loaded:\n"
    )
    out.append(_table(rows, ["domains a rule's findings carry", "rules", "which"]))
    out.append("")
    out.append(
        "Exactly one rule spans two domains on its own (`ATH-003`, endpoint + "
        "network), and it does so *within a single finding* -- which is one stage "
        "described twice, not two stages, so it fails condition 2 by itself.\n"
    )
    out.append(
        "For findings from two different domains to land in one case, "
        "`ath.correlation.correlator.score_pair` must find a **structural** signal "
        "between them. Of its six, four (`shared_evidence`, `same_process`, "
        "`process_lineage`, `sibling_lineage`) require the two findings to cite the "
        "same telemetry event or the same process instance, which two different "
        "canonical tables cannot do across the endpoint/identity/control-plane "
        "boundary except where a rule reads both. `host_movement` needs a directed "
        "host relationship, which no cloud or Kubernetes finding carries. That leaves "
        "`auth_then_exec`, and it is gated by a **hardcoded rule-id allowlist**:\n"
    )
    out.append(
        "```python\n"
        f"_AUTH_RULES = {sorted(_AUTH_RULES)}\n"
        f"_REMOTE_EXEC_RULES = {sorted(_REMOTE_EXEC_RULES)}\n"
        "```\n"
    )
    out.append(
        "So the identity -> endpoint link this project can form at all is exactly "
        "`ATH-005`/`ATH-006` followed by `ATH-007` on the same host inside the "
        "`auth_exec_window`. **No pair of rule ids outside that product can ever "
        "produce a cross-domain case**, whatever the telemetry contains -- an identity "
        "finding and a control-plane finding about the same AWS principal cannot be "
        "correlated by this codebase today. That is the structural reason for every "
        "row in the tables above, and it is the same stale-allowlist failure mode "
        "`ath.agent.specialists.Specialist` documents having removed from the "
        "specialist gates, still in place one layer down. VERIFIED FROM CODE.\n"
    )
    return "\n".join(out)


