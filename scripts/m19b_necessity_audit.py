"""M19b T4: audit every corpus and case this repository can build for cross-specialist
necessity, and write ``reports/m19b/necessity/AUDIT.{md,json}``.

What this script does and does not do
--------------------------------------
It **loads** every corpus through the same adapters the pipeline uses, **hunts**,
**triages** and **correlates** exactly as ``scripts/m19_ablation.py`` does, and then
runs arm A's deterministic investigation on every case so the eligibility it reports is
the eligibility the orchestrator actually produced. It changes no rule, no threshold and
no fixture, calls no model, and writes nothing outside ``reports/m19b/necessity/``.

Where the data lives
---------------------
``data/external/`` is gitignored and exists only in the primary checkout, so this script
takes ``--external`` and defaults to a sibling checkout's copy. A corpus whose files are
not present is recorded as ``UNAVAILABLE`` with the path that was missing -- never
silently omitted, because "this corpus has no cross-domain cases" and "this corpus was
not loaded" are the two answers it would be most damaging to confuse.

Usage::

    python scripts/m19b_necessity_audit.py --corpora fast
    python scripts/m19b_necessity_audit.py            # every corpus, DEDALE included
"""

